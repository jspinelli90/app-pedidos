require('../test-support/authenticated-server.cjs');
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

test('valida en el servidor y exige revisión privada antes de confirmar o despachar', async t => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'address-test-'));
  process.env.DATA_DIR = dir; process.env.PORT = '0'; process.env.SUPABASE_URL = ''; process.env.SUPABASE_SERVICE_ROLE_KEY = '';
  const address = require('../lib/delivery-address');
  let validation = { status: 'mismatch', message: 'La dirección corresponde a CABA.' };
  const check = t.mock.method(address, 'checkDeliveryAddress', async () => validation);
  const { server, startServer } = require('../server'); await startServer();
  t.after(async () => { await new Promise(resolve => server.close(resolve)); fs.rmSync(dir, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = async (url, method = 'GET', body) => { const res = await fetch(base + url, { method, headers: { 'Content-Type': 'application/json' }, body: body ? JSON.stringify(body) : undefined }); return { status: res.status, data: await res.json() }; };
  const policy = (await call('/api/public-order-policy?deliveryType=DELIVERY')).data;
  const payload = { customer: 'Prueba', phone: '1155551234', detail: 'Asado', deliveryType: 'DELIVERY', address: 'Cabildo 3200 - Olivos - Vicente Lopez', prepDate: policy.minDate,
    addressValidation: { status: 'verified' }, reviewed: true };
  assert.equal((await call('/api/public-orders', 'POST', payload)).status, 422);
  assert.equal((await call('/api/orders')).data.length, 0);
  validation = { status: 'review', reason: 'ambiguous_address', message: 'Dirección pendiente de revisión.' };
  const submitted = await call('/api/public-orders', 'POST', payload);
  assert.equal(submitted.status, 201); assert.equal(submitted.data.addressValidation.status, 'review');
  let order = (await call('/api/orders')).data[0];
  const endpoint = `/api/orders/${order.id}`;
  for (const status of ['Nuevo', 'Preparado', 'Despachado']) {
    assert.equal((await call(endpoint, 'PUT', { ...order, status, addressValidation: { status: 'manual' }, reviewed: true })).status, 409);
  }
  assert.equal((await call('/api/orders/dispatch', 'POST', { orders: [{ id: order.id, updatedAt: order.updatedAt }] })).status, 409);
  assert.equal((await call(endpoint + '/review-address', 'POST', { reviewed: true, updatedAt: 'stale', address: order.address })).status, 409);
  assert.equal((await call(endpoint + '/review-address', 'POST', { updatedAt: order.updatedAt, address: order.address })).status, 400);
  assert.equal((await call(endpoint + '/review-address', 'POST', { reviewed: true, updatedAt: order.updatedAt, address: order.address })).status, 200);
  order = (await call('/api/orders')).data[0];
  assert.equal(order.addressValidation.status, 'manual'); assert.equal(order.addressValidation.reviewedByUserId, 'test-user');
  let changed = await call(endpoint, 'PUT', { ...order, status: 'Nuevo' });
  assert.equal(changed.status, 200);
  assert.equal((await call(endpoint, 'PUT', { ...changed.data, address: 'Otra dirección 123', status: 'Preparado' })).status, 409);
  changed = await call(endpoint, 'PUT', { ...changed.data, address: 'Otra dirección 123', status: 'Provisorio' });
  assert.equal(changed.status, 200); assert.equal(changed.data.addressValidation.status, 'review');
  assert.ok((await call('/api/movements')).data.some(item => item.action === 'Dirección revisada'));
  const calls = check.mock.callCount();
  assert.equal((await call('/api/public-orders', 'POST', { ...payload, deliveryType: 'RETIRO' })).status, 201);
  assert.equal(check.mock.callCount(), calls);
  validation = { status: 'verified', source: 'Georef' };
  const structured = { ...payload, address: 'Domicilio distinto que no debe guardarse', streetAddress: 'Uruguay 2409', district: 'San Fernando', locality: 'San Fernando' };
  assert.equal((await call('/api/public-orders', 'POST', structured)).status, 201);
  const stored = (await call('/api/orders')).data.find(item => item.addressValidation?.status === 'verified');
  assert.equal(stored.address, 'Uruguay 2409 - San Fernando - San Fernando');
  validation = { status: 'review', reason: 'ambiguous_address', message: 'Regla anterior.' };
  const pendingSubmission = await call('/api/public-orders', 'POST', { ...payload, address: 'Cuyo 1000 - Martinez - San Isidro' });
  assert.equal(pendingSubmission.status, 201);
  const pendingOrder = (await call('/api/orders')).data.find(item => item.number === pendingSubmission.data.number);
  validation = { status: 'mismatch', message: 'No existe en el partido elegido.' };
  assert.equal((await call(`/api/orders/${pendingOrder.id}`, 'PUT', { ...pendingOrder, status: 'Nuevo' })).status, 422);
  assert.equal((await call('/api/orders')).data.find(item => item.id === pendingOrder.id).status, 'Provisorio');
  validation = { status: 'verified', policy: 'district-v2', source: 'Georef' };
  const automatic = await call(`/api/orders/${pendingOrder.id}`, 'PUT', { ...pendingOrder, status: 'Nuevo' });
  assert.equal(automatic.status, 200);
  assert.equal(automatic.data.status, 'Nuevo'); assert.equal(automatic.data.addressValidation.status, 'verified');
  assert.equal(automatic.data.addressValidation.policy, 'district-v2');
});
